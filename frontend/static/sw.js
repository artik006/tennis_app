// ===============================
// ЭТО ФАЙЛ service worker (sw.js)
// Он делает сайт устанавливаемым как приложение
// Без него телефон не даст добавить сайт на главный экран
// ===============================

// Срабатывает при установке приложения
self.addEventListener("install", () => {
    console.log("Service Worker установлен");
});

// Обрабатывает все запросы сайта
// Сейчас просто пропускает их как есть
// (позже можно добавить офлайн-режим)
self.addEventListener("fetch", (event) => {
    event.respondWith(fetch(event.request));
});
